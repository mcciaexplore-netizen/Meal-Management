CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name CITEXT NOT NULL,
    is_active SMALLINT NOT NULL DEFAULT 1,
    PRIMARY KEY (id),
    CONSTRAINT uq_departments_name UNIQUE (name),
    CONSTRAINT chk_department_name CHECK (CHAR_LENGTH(TRIM(name)) > 0),
    CONSTRAINT chk_department_active CHECK (is_active IN (0, 1)),
    CONSTRAINT chk_departments_name_length CHECK (CHAR_LENGTH(name) <= 100)
);

CREATE TABLE employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    employee_code CITEXT NOT NULL,
    full_name CITEXT NOT NULL,
    email CITEXT NOT NULL,
    company_name CITEXT NULL,
    phone CITEXT NULL,
    department_id BIGINT NOT NULL,
    is_active SMALLINT NOT NULL DEFAULT 1,
    selfie_object_key VARCHAR(512) NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT (statement_timestamp() AT TIME ZONE 'UTC'),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT (statement_timestamp() AT TIME ZONE 'UTC'),
    PRIMARY KEY (id),
    CONSTRAINT uq_employees_code UNIQUE (employee_code),
    CONSTRAINT fk_employees_department
        FOREIGN KEY (department_id) REFERENCES departments (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_employee_required CHECK (
        CHAR_LENGTH(TRIM(employee_code)) > 0
        AND CHAR_LENGTH(TRIM(full_name)) > 0
        AND CHAR_LENGTH(TRIM(email)) > 0
    ),
    CONSTRAINT chk_employee_active CHECK (is_active IN (0, 1)),
    CONSTRAINT chk_employee_selfie CHECK (
        selfie_object_key IS NULL OR CHAR_LENGTH(TRIM(selfie_object_key)) > 0
    ),
    CONSTRAINT chk_employee_company CHECK (
        company_name IS NULL OR CHAR_LENGTH(TRIM(company_name)) > 0
    ),
    CONSTRAINT chk_employee_phone CHECK (
        phone IS NULL OR CHAR_LENGTH(TRIM(phone)) > 0
    ),
    CONSTRAINT chk_employees_employee_code_length CHECK (CHAR_LENGTH(employee_code) <= 32),
    CONSTRAINT chk_employees_full_name_length CHECK (CHAR_LENGTH(full_name) <= 150),
    CONSTRAINT chk_employees_email_length CHECK (CHAR_LENGTH(email) <= 254),
    CONSTRAINT chk_employees_company_name_length CHECK (CHAR_LENGTH(company_name) <= 150),
    CONSTRAINT chk_employees_phone_length CHECK (CHAR_LENGTH(phone) <= 32)
);

CREATE TABLE staff_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    display_name VARCHAR(150) NOT NULL,
    email CITEXT NOT NULL,
    password_hash VARCHAR(255) NULL,
    is_scanner SMALLINT NOT NULL DEFAULT 0,
