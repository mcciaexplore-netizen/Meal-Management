CREATE TABLE qr_credentials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    kind VARCHAR(32) NOT NULL,
    employee_id BIGINT NULL,
    token_hash BYTEA NOT NULL,
    token_ciphertext BYTEA NULL,
    issued_by BIGINT NOT NULL,
    issued_at TIMESTAMP(6) NOT NULL DEFAULT (statement_timestamp() AT TIME ZONE 'UTC'),
    expires_at TIMESTAMP(6) NULL,
    revoked_at TIMESTAMP(6) NULL,
    revoked_by BIGINT NULL,
    revocation_reason VARCHAR(255) NULL,
    unrevoked_employee_id BIGINT GENERATED ALWAYS AS ( CASE WHEN kind = 'EMPLOYEE' AND revoked_at IS NULL THEN employee_id ELSE NULL END ) STORED,
    PRIMARY KEY (id),
    CONSTRAINT uq_qr_token_hash UNIQUE (token_hash),
    CONSTRAINT uq_qr_id_kind UNIQUE (id, kind),
    CONSTRAINT uq_qr_employee_kind UNIQUE (id, employee_id, kind),
    CONSTRAINT uq_qr_unrevoked_employee UNIQUE (unrevoked_employee_id),
    CONSTRAINT fk_qr_employee
        FOREIGN KEY (employee_id) REFERENCES employees (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_qr_issuer
        FOREIGN KEY (issued_by) REFERENCES staff_accounts (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_qr_revoker
        FOREIGN KEY (revoked_by) REFERENCES staff_accounts (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_qr_owner CHECK (
        (kind = 'EMPLOYEE' AND employee_id IS NOT NULL)
        OR (kind = 'MASTER' AND employee_id IS NULL)
    ),
    CONSTRAINT chk_qr_expiry CHECK (
        expires_at IS NULL OR expires_at > issued_at
    ),
    CONSTRAINT chk_qr_revocation CHECK (
        (revoked_at IS NULL AND revoked_by IS NULL AND revocation_reason IS NULL)
        OR (
            revoked_at IS NOT NULL AND revoked_at >= issued_at
            AND revoked_by IS NOT NULL AND revocation_reason IS NOT NULL
            AND CHAR_LENGTH(TRIM(revocation_reason)) > 0
        )
    ),
    CONSTRAINT chk_qr_credentials_kind_enum CHECK (kind IN ('EMPLOYEE', 'MASTER'))
);

CREATE TABLE master_qr_allocations (
    qr_id BIGINT NOT NULL,
    kind VARCHAR(32) NOT NULL DEFAULT 'MASTER',
    company_name VARCHAR(150) NOT NULL,
    contact_name VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL,
    phone VARCHAR(32) NOT NULL,
    meal_limit INTEGER NOT NULL,
    meals_used INTEGER NOT NULL DEFAULT 0,
