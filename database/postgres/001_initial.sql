CREATE FUNCTION meal_touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
    IF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
        NEW.updated_at := (statement_timestamp() AT TIME ZONE 'UTC')::timestamp(6);
    END IF;
    RETURN NEW;
END
