    CONSTRAINT chk_staff_scanner CHECK (is_scanner IN (0, 1)),
    CONSTRAINT chk_staff_active CHECK (is_active IN (0, 1)),
    CONSTRAINT chk_staff_accounts_email_length CHECK (CHAR_LENGTH(email) <= 254)
);

