CREATE FUNCTION meal_email_queue_approval_guard() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
    IF NEW.id IS DISTINCT FROM OLD.id OR NEW.qr_id IS DISTINCT FROM OLD.qr_id
        OR NEW.recipient_email IS DISTINCT FROM OLD.recipient_email
        OR NEW.created_at IS DISTINCT FROM OLD.created_at
        OR NEW.delivery_mode IS DISTINCT FROM OLD.delivery_mode
        OR NEW.bulk_batch_id IS DISTINCT FROM OLD.bulk_batch_id
        OR (OLD.approved_by_staff_id IS NOT NULL AND (
            NEW.approved_by_staff_id IS DISTINCT FROM OLD.approved_by_staff_id
            OR NEW.approved_at IS DISTINCT FROM OLD.approved_at
        )) THEN
        RAISE EXCEPTION USING ERRCODE = '45000', MESSAGE = 'Email approval attribution is immutable';
    END IF;
    IF OLD.approved_by_staff_id IS NULL AND NEW.approved_by_staff_id IS NOT NULL
        AND NOT EXISTS (
            SELECT 1 FROM staff_accounts s JOIN staff_account_roles r ON r.staff_id = s.id
            WHERE s.id = NEW.approved_by_staff_id AND s.is_active = 1
                AND s.is_scanner = 0 AND r.role_code = 'ADMIN'
        ) THEN
        RAISE EXCEPTION USING ERRCODE = '45000', MESSAGE = 'Email approval requires an administrator';
    END IF;
    RETURN NEW;
END
