CREATE FUNCTION meal_qr_identity_immutable() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
    IF NEW.id IS DISTINCT FROM OLD.id
        OR NEW.kind IS DISTINCT FROM OLD.kind
        OR NEW.employee_id IS DISTINCT FROM OLD.employee_id
        OR NEW.token_hash IS DISTINCT FROM OLD.token_hash
        OR NEW.issued_by IS DISTINCT FROM OLD.issued_by
        OR NEW.issued_at IS DISTINCT FROM OLD.issued_at
    THEN
        RAISE EXCEPTION USING ERRCODE = '45000', MESSAGE = 'QR identity is immutable';
    END IF;
    IF OLD.revoked_at IS NOT NULL AND (
        NEW.revoked_at IS DISTINCT FROM OLD.revoked_at
        OR NEW.revoked_by IS DISTINCT FROM OLD.revoked_by
        OR NEW.revocation_reason IS DISTINCT FROM OLD.revocation_reason
    ) THEN
        RAISE EXCEPTION USING ERRCODE = '45000', MESSAGE = 'QR revocation is permanent';
    END IF;
    RETURN NEW;
END
$fn$//

CREATE FUNCTION meal_serving_request_guard() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
    IF NEW.id IS DISTINCT FROM OLD.id
        OR NEW.payload_hash IS DISTINCT FROM OLD.payload_hash
        OR NEW.created_at IS DISTINCT FROM OLD.created_at
    THEN
        RAISE EXCEPTION USING ERRCODE = '45000', MESSAGE = 'Request identity is immutable';
    END IF;
    IF (OLD.scan_bound_at IS NOT NULL OR OLD.status <> 'PENDING') AND (
        NEW.scan_authorization_id IS DISTINCT FROM OLD.scan_authorization_id
        OR NEW.scan_visitor_hash IS DISTINCT FROM OLD.scan_visitor_hash
        OR NEW.scan_bound_at IS DISTINCT FROM OLD.scan_bound_at
    ) THEN
        RAISE EXCEPTION USING ERRCODE = '45000', MESSAGE = 'Scan binding is immutable';
    END IF;
    IF OLD.status <> 'PENDING' AND (
        NEW.status IS DISTINCT FROM OLD.status
        OR NEW.rejection_code IS DISTINCT FROM OLD.rejection_code
        OR NEW.completed_at IS DISTINCT FROM OLD.completed_at
    ) THEN
        RAISE EXCEPTION USING ERRCODE = '45000', MESSAGE = 'Finalized requests are immutable';
    END IF;
    RETURN NEW;
END
